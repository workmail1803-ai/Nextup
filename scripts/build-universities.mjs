// Build the world university directory from the open Hipolabs dataset.
//
// Source: https://github.com/Hipo/university-domains-list (CC — ~10k institutions
// with name, country, official web pages). We bake it into a static JSON so the
// app stays API-free at runtime. Re-run to refresh:
//   1) download world_universities_and_domains.json to the repo parent
//   2) node scripts/build-universities.mjs
//
// Output: src/lib/eligibility/world-universities.ts  (compact tuples [name, country, url])

import { readFileSync, writeFileSync } from "node:fs";

const SRC = "D:/NEXTUP_REFACTOR/world_universities.json";
const OUT = "src/lib/eligibility/world-universities.ts";

const RENAME = {
  "Korea, Republic of": "South Korea",
  "Korea, Democratic People's Republic of": "North Korea",
  "Taiwan, Province of China": "Taiwan",
  "Russian Federation": "Russia",
  "Turkiye": "Türkiye",
  "Viet Nam": "Vietnam",
  "Bolivia, Plurinational State of": "Bolivia",
  "Moldova, Republic of": "Moldova",
  "Tanzania, United Republic of": "Tanzania",
  "Venezuela, Bolivarian Republic of": "Venezuela",
  "Iran, Islamic Republic of": "Iran",
  "Holy See (Vatican City State)": "Vatican City",
  "Congo, the Democratic Republic of the": "DR Congo",
  "Syrian Arab Republic": "Syria",
  "Lao People's Democratic Republic": "Laos",
  "Brunei Darussalam": "Brunei",
  "Macao": "Macau",
};

const raw = JSON.parse(readFileSync(SRC, "utf8"));
const seen = new Set();
const out = [];

for (const u of raw) {
  const web = u.web_pages && u.web_pages[0];
  const name = (u.name || "").trim();
  if (!web || !name) continue;
  const country = RENAME[u.country] || u.country;
  const key = `${name}|${country}`.toLowerCase();
  if (seen.has(key)) continue;
  seen.add(key);
  const site = web.trim().replace(/^http:\/\//, "https://");
  out.push([name, country, site]);
}

out.sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));

const header =
  "// AUTO-GENERATED by scripts/build-universities.mjs — do not edit by hand.\n" +
  "// Open data from github.com/Hipo/university-domains-list. Tuples: [name, country, url].\n\n" +
  "export const WORLD_RAW: [string, string, string][] = ";
writeFileSync(OUT, header + JSON.stringify(out) + ";\n");
console.log(`wrote ${out.length} universities to ${OUT}`);
